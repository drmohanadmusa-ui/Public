// Builds index.ts (the file pasted into Supabase) from the phone script's parser + handler.js.
// Run after changing sms/ledger_sms_logger.js or handler.js:  node dev/ledgeros/edge/sms-ingest/build.js
// The main test suite fails if index.ts is out of date.
const fs = require("fs"), path = require("path");
function build() {
  const src = fs.readFileSync(path.join(__dirname, "..", "..", "sms", "ledger_sms_logger.js"), "utf8");
  const a = src.indexOf("const FX_TO_SAR"), b = src.indexOf("function localFm()");
  if (a < 0 || b < 0 || b < a) throw new Error("parser markers not found in ledger_sms_logger.js");
  const head = "// LedgerOS SMS ingest: a Supabase Edge Function. GENERATED by build.js: don't edit here, edit\n" +
    "// sms/ledger_sms_logger.js (the parser) or edge/sms-ingest/handler.js, then run build.js. Setup: edge/README.md.\n" +
    "// Plain JavaScript on purpose (valid TypeScript), so the tests can run it in Node.\n\n" +
    "// ===== parser, copied from sms/ledger_sms_logger.js =====\n";
  return head + src.slice(a, b).trimEnd() + "\n\n" + fs.readFileSync(path.join(__dirname, "handler.js"), "utf8");
}
module.exports = { build };
if (require.main === module) { fs.writeFileSync(path.join(__dirname, "index.ts"), build()); console.log("index.ts written"); }
